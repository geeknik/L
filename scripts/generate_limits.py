"""Generate shared validation constants from spec/limits.md (stdlib only)."""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    rows = re.findall(r'^\| (MAX_[A-Z_]+) \| ([0-9]+) \|',
                      (ROOT / 'spec/limits.md').read_text(), re.MULTILINE)
    if not rows or len(dict(rows)) != len(rows) or any(int(v) < 1 for _, v in rows):
        raise ValueError('Invalid shared limit table')
    outputs = {
        ROOT / 'lang/limits.py': '# Generated by scripts/generate_limits.py; do not edit.\n'
        + ''.join(f'{k} = {v}\n' for k, v in rows),
        ROOT / 'rust/src/limits.rs': '// Generated by scripts/generate_limits.py; do not edit.\n'
        + ''.join(f'pub const {k}: usize = {v};\n' for k, v in rows),
    }
    stale = []
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content)
    if stale:
        print('Stale generated limits: ' + ', '.join(stale))
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
